#!/usr/bin/env bash
#
# Creates a minimal Neos distribution with this package installed (symlinked), to run the functional tests in.
#
# Functional tests boot a full Flow application, so they can't run from the package root alone.
# Used by run-tests.sh and the GitHub CI (.github/workflows/tests.yml).
#
# Usage: Tests/Functional/setup-test-distribution.sh [target-directory]
#
# The target directory must be OUTSIDE of this package: the package is symlinked into it.
set -euo pipefail

PACKAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TARGET_DIR="${1:-${TMPDIR:-/tmp}/flowpack-listable-test-distribution}"
TARGET_DIR="${TARGET_DIR%/}"

case "$TARGET_DIR/" in
    "$PACKAGE_DIR"/*)
        echo "The target directory must be outside of the package directory ($PACKAGE_DIR)." >&2
        exit 1
        ;;
esac

mkdir -p "$TARGET_DIR"

cat > "$TARGET_DIR/composer.json" <<EOF
{
    "name": "flowpack/listable-test-distribution",
    "description": "Throwaway distribution for the functional tests of flowpack/listable - generated by Tests/Functional/setup-test-distribution.sh",
    "type": "project",
    "license": "MIT",
    "repositories": [
        {
            "type": "path",
            "url": "$PACKAGE_DIR",
            "options": {
                "symlink": true,
                "versions": {
                    "flowpack/listable": "3.6.x-dev"
                }
            }
        }
    ],
    "require": {
        "flowpack/listable": "3.6.x-dev",
        "neos/neos": "~8.3.0"
    },
    "require-dev": {
        "neos/buildessentials": "~8.3.0",
        "phpunit/phpunit": "~9.6",
        "mikey179/vfsstream": "^1.6.10"
    },
    "autoload-dev": {
        "psr-4": {
            "Neos\\\\Flow\\\\Tests\\\\": "Packages/Framework/Neos.Flow/Tests/",
            "Flowpack\\\\Listable\\\\Tests\\\\": "Packages/Application/Flowpack.Listable/Tests/"
        }
    },
    "config": {
        "vendor-dir": "Packages/Libraries",
        "bin-dir": "bin",
        "allow-plugins": {
            "neos/composer-plugin": true
        }
    },
    "scripts": {
        "post-update-cmd": "Neos\\\\Flow\\\\Composer\\\\InstallerScripts::postUpdateAndInstall",
        "post-install-cmd": "Neos\\\\Flow\\\\Composer\\\\InstallerScripts::postUpdateAndInstall"
    }
}
EOF

# Flow compiles its proxy classes in sub-processes and FunctionalTestBootstrap.php runs `./flow cache:warmup`
# via shell_exec - all of them need more than PHP's default memory_limit of 128M. run-tests.sh adds this
# directory to PHP_INI_SCAN_DIR, which reaches every PHP process it starts.
mkdir -p "$TARGET_DIR/php-ini"
echo 'memory_limit = -1' > "$TARGET_DIR/php-ini/memory-limit.ini"

mkdir -p "$TARGET_DIR/Configuration/Testing"
cat > "$TARGET_DIR/Configuration/Testing/Settings.yaml" <<'EOF'
Neos:
  Flow:
    object:
      # In the Testing context Flow reflects the test classes of all packages. The tests of neos/party 7.1
      # use PHPUnit 10 attributes, while Neos 8.3 runs PHPUnit 9 - skip them, we never run them anyway.
      includeClasses:
        'Neos.Party': ['Neos\\Party\\(?!Tests\\).*']
EOF

cd "$TARGET_DIR"
composer update --no-interaction --no-progress
